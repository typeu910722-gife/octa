# Builds app/i18n-dict.js from i18n/strings.py (and strings4.py).
#   python3 i18n/build.py               → app/i18n-dict.js
#   python3 i18n/build.py --templates   → also embeds i18n/templates.py into the local API (desktop/api/*.mjs
#                                          when present, otherwise functions/api/[[path]].js)
# Simplified Chinese is converted with OpenCC (pip install opencc-python-reimplemented).
import json, os, sys, re, glob
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..')
sys.path.insert(0, HERE)
from strings import T, P
import opencc
cc = opencc.OpenCC('tw2sp')
out = {'en': {'t': {}, 'p': []}, 'ja': {'t': {}, 'p': []}, 'zh-CN': {'t': {}, 'p': [], 'cm': {}}}
for k, (en, ja) in T.items():
    out['en']['t'][k] = en; out['ja']['t'][k] = ja; out['zh-CN']['t'][k] = cc.convert(k)
for rx, en, ja in P:
    out['en']['p'].append([rx, en]); out['ja']['p'].append([rx, ja])
# character map for Simplified Chinese: covers text with names or numbers in it
chars = set(''.join(T.keys()) + ''.join(p[0] for p in P))
for f in [os.path.join(ROOT, 'app', 'index.html')] + glob.glob(os.path.join(ROOT, 'app', 'js', '*.js')):
    chars |= set(open(f, encoding='utf8').read())
for ch in chars:
    if '㐀' <= ch <= '鿿':
        s = cc.convert(ch)
        if s != ch and len(s) == 1: out['zh-CN']['cm'][ch] = s
out['zh-CN']['cm'] = dict(sorted(out['zh-CN']['cm'].items()))
js = '// Generated by i18n/build.py — edit i18n/strings.py / strings4.py instead.\nwindow.OCTA_I18N=' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n'
open(os.path.join(ROOT, 'app', 'i18n-dict.js'), 'w', encoding='utf8').write(js)
print('keys', len(T), 'patterns', len(P), 'charmap', len(out['zh-CN']['cm']), 'bytes', len(js.encode()))

if '--templates' in sys.argv:
    # Template bots per language → embedded in the API
    from templates import TPL
    def conv(x):
        # markers the API parses stay in Traditional Chinese (⏰例行任務：…｜每10分鐘監看 url｜…, （略過）)
        if isinstance(x, str): return re.sub(r'每(\d+)分钟监看', r'每\1分鐘監看', cc.convert(x).replace('暱', '昵').replace('⏰例行任务：', '⏰例行任務：').replace('（略过）', '（略過）'))
        if isinstance(x, list): return [i if isinstance(i, str) and re.match(r'^[a-z]\d?$', i) else conv(i) for i in x]
        if isinstance(x, dict): return {k: conv(v) for k, v in x.items()}
        return x
    TPL['zh-CN'] = conv(TPL['zh-TW'])
    targets = [f for f in glob.glob(os.path.join(ROOT, 'desktop', 'api', '*.mjs')) if '// Templates offered in the app' in open(f, encoding='utf8').read()]
    if not targets: targets = [os.path.join(ROOT, 'functions', 'api', '[[path]].js')]
    for api in targets:
        s = open(api, encoding='utf8').read()
        # replace only the TEMPLATES_I18N literal (code after it must stay)
        a = s.index('// Templates offered in the app'); b = s.index('\n};\n', a) + len('\n};\n')
        s = s[:a] + '// Templates offered in the app, per interface language (generated from i18n/templates.py)\nconst TEMPLATES_I18N = ' + json.dumps(TPL, ensure_ascii=False, indent=1) + ';\n' + s[b:]
        open(api, 'w', encoding='utf8').write(s)
        print('templates embedded in', os.path.relpath(api, ROOT))
